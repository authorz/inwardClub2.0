INSERT INTO wallet_ledger_entries
  (account_id, member_id, asset_type, direction, amount, balance_after,
   reason, source_type, source_id, idem_key, created_at)
SELECT wa.id,
       wa.member_id,
       'growth_value',
       'credit',
       l.growth_value,
       wa.available_amount + l.growth_value,
       'legacy_recharge_growth',
       'legacy_v1',
       l.legacy_user_id,
       CONCAT('growth_legacy_v1:v43:', wa.member_id),
       NOW()
FROM members m
JOIN legacy_recharge_growth_totals l ON l.legacy_user_id = m.legacy_user_id
JOIN wallet_accounts wa ON wa.member_id = m.id AND wa.asset_type = 'growth_value'
WHERE l.growth_value > 0;

UPDATE members m
JOIN legacy_recharge_growth_totals l ON l.legacy_user_id = m.legacy_user_id
JOIN wallet_accounts wa ON wa.member_id = m.id AND wa.asset_type = 'growth_value'
SET wa.available_amount = wa.available_amount + l.growth_value,
    wa.version = wa.version + 1,
    wa.updated_at = NOW()
WHERE l.growth_value > 0;

